import assert from 'node:assert/strict';
import { planNotifications } from '../mobile/schedule.js';
const item = { id: 'a', kind: 'item', type: 'task', title: '운동', date: '2026-11-17', time: '00:15', remind: 30 };
const now = new Date(2026, 10, 16, 23, 0);
const plan = (r, st = {}, focus = null) => planNotifications(r, st, focus, now);
assert.equal(plan({ a: item })[0].schedule.at.getDate(), 16);
assert.equal(plan({ a: item })[0].schedule.at.getHours(), 23);
assert.equal(plan({ a: { ...item, deleted: true } }).length, 0);
assert.equal(plan({ a: { ...item, done: true } }).length, 0);
assert.equal(plan({ a: { ...item, remind: -1 } }).length, 0);
assert.equal(plan({ a: { ...item, repeat: 'daily', until: '2026-11-19', doneDates: ['2026-11-18'] } }).length, 2);
assert.equal(plan({}, { morning: '08:00', evening: '21:00' }).length, 58);
assert.equal(plan({}, {}, { endsAt: now.getTime() + 60000, total: 60 }).at(-1).id, 10001);
assert.equal(plan({}, {}, { endsAt: now.getTime() + 60000, total: 60, paused: true }).length, 0);
const many = Object.fromEntries(Array.from({ length: 20 }, (_, i) => [i, { ...item, id: String(i), repeat: 'daily' }]));
const limited = plan(many);
assert.equal(limited.length, 400);
assert.equal(new Set(limited.map(n => n.id)).size, 400);
assert.ok(limited.every((n, i) => i === 0 || n.schedule.at >= limited[i - 1].schedule.at));
console.log('mobile: 12 assertions passed');
