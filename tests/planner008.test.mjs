import assert from 'node:assert/strict';
import * as S from '../store.js';
import { CATEGORIES, CATEGORY_FIELDS } from '../categories.js';
import { widgetSnapshot } from '../mobile/widget.js';
const day='2026-11-17';
const old={id:'old',kind:'item',type:'task',date:day,title:'기존 기록',updatedAt:1};
const inbox={...old,id:'inbox',date:'',repeat:'daily',category:'reading',categoryDetails:{reading:{reflection:'기억할 문장'}}};
const second={...old,id:'second',title:'두 번째',updatedAt:2,repeat:'daily'};
let records={old,inbox,second};
assert.equal(S.occursOn(inbox,day),false);
assert.deepEqual(S.overdue(records,'2026-11-18').map(r=>r.id),['old']);
assert.deepEqual(S.inboxItems(records).map(r=>r.id),['inbox']);
assert.equal(S.search(records,'기억할 문장')[0].id,'inbox');
const reordered=S.reorderDay(records,day,'second',-1);
records=S.merge(records,Object.fromEntries(reordered.map(r=>[r.id,r])));
assert.deepEqual(S.itemsOn(records,day).map(r=>r.id),['second','old']);
assert.equal(second.dayOrder,undefined); // immutable / existing data preserved
assert.equal(S.itemsOn(records,'2026-11-18')[0].dayOrder?.['2026-11-18'],undefined);
const moved={...inbox,date:day,repeat:'none',updatedAt:3};
records=S.merge(records,{inbox:moved});
assert.equal(S.inboxItems(records).length,0);
assert.equal(S.itemsOn(records,day).length,3);
assert.equal(S.validateImport({records:JSON.parse(JSON.stringify(records))}).inbox.categoryDetails.reading.reflection,'기억할 문장');
assert.equal(widgetSnapshot(records,day).days[day].count,3);
assert.equal(widgetSnapshot({...records,old:{...old,done:true}},day).days[day].count,2);
assert.equal(new Set(CATEGORIES.map(c=>c.id)).size,CATEGORIES.length);
assert.equal(CATEGORIES.length,18);
for(const c of CATEGORIES) assert.ok(Array.isArray(CATEGORY_FIELDS[c.id]));
assert.deepEqual(S.reorderDay(records,day,'second',-1),[]);
assert.equal(S.mergeRecord({...old,updatedAt:10,deleted:true},{...old,updatedAt:9}).deleted,true);
console.log('planner008: inbox/order/migration/category fields/widget snapshot passed');
