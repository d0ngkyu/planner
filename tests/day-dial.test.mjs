import assert from 'node:assert/strict';
import {daySegments,minutes,ringPath,dialView} from '../day-dial.js';
const date='2026-11-17';
const item=(id,time,end,extra={})=>({id,kind:'item',type:'event',date,time,end,title:id,updatedAt:1,...extra});
const records={a:item('a','09:00','11:00'),b:item('b','10:00','12:00'),c:item('c','12:00','13:00'),night:item('night','23:00','02:00',{date:'2026-11-16'}),none:item('none','',''),bad:item('bad','25:30',''),open:item('open','23:30',''),inbox:item('inbox','10:00','11:00',{date:''})};
const model=daySegments(records,date);
assert.equal(model.segments.length,5);
assert.equal(model.lanes,2);
const get=id=>model.segments.find(s=>s.item.id===id);
assert.equal(get('a').lane,0); assert.equal(get('b').lane,1); assert.equal(get('c').lane,0);
assert.equal(get('night').from,0); assert.equal(get('night').to,120);
assert.equal(get('night').origin,'2026-11-16');
assert.equal(get('open').estimated,true); assert.equal(get('open').to,1440);
assert.equal(daySegments(records,'2026-11-18').segments[0].to,30);
assert.equal(minutes('00:00'),0); assert.equal(minutes('24:00'),null);
assert.equal(minutes('01:59'),119); assert.equal(minutes('9:00'),null);
assert.ok(!ringPath(0,1440,50,140).includes('NaN'));
assert.equal((ringPath(0,1440,50,140).match(/M /g)||[]).length,2);
const daily={x:item('x','23:00','01:00',{date:'2026-11-16',repeat:'daily',doneDates:['2026-11-16']})};
const both=daySegments(daily,date).segments;
assert.equal(both.length,2); assert.equal(both[0].done,true); assert.equal(both[1].done,false);
assert.equal(daySegments({x:item('x','10:00','10:00')},date).segments[0].to,660);
const html=dialView({x:item('x','10:00','11:00',{title:'<script>bad</script>',color:'" onload="alert(1)'})},date,null);
assert.ok(!html.includes('<script>')); assert.ok(html.includes('&lt;script&gt;')); assert.ok(!html.includes('onload='));
assert.ok(dialView({},date,null).includes('아직 시간 있는 일정'));
assert.ok(dialView(records,date,'night@2026-11-16').includes('전날부터 이어지는 일정'));
console.log('day dial: overlaps, midnight, repeats, invalid/untimed, defaults, geometry and escaping passed');
